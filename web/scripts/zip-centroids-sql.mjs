// Builds supabase/seed/zip_centroids.sql (US ZCTA centroids, ~33.8k rows) from
// the US Census 2024 Gazetteer, for the distance filter (listing_distances).
// Public data; run once per Supabase project, after the migrations:
//   node scripts/zip-centroids-sql.mjs            # downloads the Gazetteer
//   node scripts/zip-centroids-sql.mjs path/to/2024_Gaz_zcta_national.txt
// Then run the SQL in the Supabase SQL editor (or psql). Re-running is safe.
import fs from "node:fs";
import { execFileSync } from "node:child_process";
import os from "node:os";
import path from "node:path";

const GAZETTEER_URL =
  "https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_zcta_national.zip";

let file = process.argv[2];
if (!file) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "gaz-"));
  const zip = path.join(dir, "gaz.zip");
  const res = await fetch(GAZETTEER_URL);
  if (!res.ok) throw new Error(`Download failed: ${res.status}`);
  fs.writeFileSync(zip, Buffer.from(await res.arrayBuffer()));
  execFileSync("unzip", ["-o", "-q", zip, "-d", dir]);
  file = fs.readdirSync(dir).map((f) => path.join(dir, f)).find((f) => f.endsWith(".txt"));
  if (!file) throw new Error("Gazetteer .txt not found in zip");
}

const lines = fs.readFileSync(file, "utf8").trim().split(/\r?\n/);
const header = lines.shift().split("\t").map((h) => h.trim());
const iZip = header.indexOf("GEOID");
const iLat = header.indexOf("INTPTLAT");
const iLng = header.indexOf("INTPTLONG");
if (iZip < 0 || iLat < 0 || iLng < 0) throw new Error("Unexpected Gazetteer columns: " + header.join(","));

const rows = [];
for (const line of lines) {
  const c = line.split("\t").map((x) => x.trim());
  const zip = c[iZip];
  const lat = Number(c[iLat]);
  const lng = Number(c[iLng]);
  if (/^\d{5}$/.test(zip) && Number.isFinite(lat) && Number.isFinite(lng)) rows.push(`('${zip}',${lat},${lng})`);
}

const out = ["-- Generated by scripts/zip-centroids-sql.mjs from the US Census 2024 Gazetteer (ZCTA).", "begin;"];
for (let i = 0; i < rows.length; i += 1000) {
  out.push(
    `insert into public.zip_centroids (zip, lat, lng) values\n${rows.slice(i, i + 1000).join(",\n")}\non conflict (zip) do update set lat = excluded.lat, lng = excluded.lng;`
  );
}
out.push("commit;");
const dest = new URL("../supabase/seed/zip_centroids.sql", import.meta.url);
fs.mkdirSync(new URL("../supabase/seed/", import.meta.url), { recursive: true });
fs.writeFileSync(dest, out.join("\n") + "\n");
console.log(`Wrote ${rows.length} ZIP centroids to supabase/seed/zip_centroids.sql`);
